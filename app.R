check_observation_project_link <- function(obs_id, project_id) {
  if (is.null(obs_id) || !nzchar(obs_id) || is.null(project_id) || !nzchar(project_id)) return(FALSE)
  res <- try(
    httr::GET(
      url = paste0("https://api.inaturalist.org/v1/observations/", obs_id),
      query = list(include_new_projects = "true"),
      httr::add_headers(Accept = "application/json"),
      httr::timeout(20)
    ),
    silent = TRUE
  )
  if (inherits(res, "try-error") || httr::status_code(res) >= 300) return(FALSE)
  parsed <- try(httr::content(res, as = "parsed", type = "application/json"), silent = TRUE)
  if (inherits(parsed, "try-error") || is.null(parsed$results) || length(parsed$results) == 0) return(FALSE)
  o <- parsed$results[[1]]
  project_ids <- o$project_ids %||% integer(0)
  non_trad <- o$non_traditional_projects %||% list()
  non_trad_ids <- suppressWarnings(vapply(non_trad, function(x) x$id %||% NA_integer_, numeric(1)))
  as.integer(project_id) %in% c(project_ids, non_trad_ids)
}

inat_get_taxon_name <- function(obs_id) {
  if (is.na(obs_id) || !nzchar(obs_id)) return(NA_character_)
  
  url <- paste0("https://api.inaturalist.org/v1/observations/", obs_id)
  
  res <- try(
    httr::GET(url, query = list(locale = "en"), httr::timeout(20)),
    silent = TRUE
  )
  if (inherits(res, "try-error")) return(NA_character_)
  if (httr::status_code(res) >= 300L) return(NA_character_)
  
  j <- try(httr::content(res, as = "parsed", type = "application/json"), silent = TRUE)
  if (inherits(j, "try-error") || is.null(j$results) || length(j$results) == 0) {
    return(NA_character_)
  }
  
  o <- j$results[[1]]
  
  if (!is.null(o$community_taxon) && !is.null(o$community_taxon$name)) return(o$community_taxon$name)
  if (!is.null(o$taxon) && !is.null(o$taxon$name)) return(o$taxon$name)
  if (!is.null(o$species_guess)) return(o$species_guess)
  
  NA_character_
}

push_to_inaturalist <- function(
    token,
    jwt = NULL,
    project_id = NULL,
    species_name,
    loc = NULL,
    photos = NULL,
    plant_origin = "cultivated"
) {
  if (is.null(token)) {
    warning("No iNaturalist token (NULL), skipping upload")
    return(NA_character_)
  }
  
  access_token <- tryCatch({
    at <- token$access_token
    if (is.null(at) || length(at) == 0) return("")
    as.character(at[1])
  }, error = function(e) "")
  
  if (!nzchar(access_token)) {
    warning("No iNaturalist access_token, skipping upload")
    return(NA_character_)
  }
  
  # Survey comments remain in the OneSTOP research database and
  # are deliberately not copied into the public iNaturalist record.
  body <- list(
    "observation[species_guess]"       = species_name,
    "observation[observed_on_string]" = format(Sys.time(), "%Y-%m-%d %H:%M:%S"),
    "observation[time_zone]"          = "UTC"
  )
  
  if (!is.null(loc) && !is.null(loc$lat) && !is.null(loc$lon)) {
    body[["observation[latitude]"]]  <- loc$lat
    body[["observation[longitude]"]] <- loc$lon
  }
  
  res <- try(
    httr::POST(
      url = INAT_OBS_URL,
      httr::add_headers(Authorization = paste("Bearer", access_token)),
      body = body,
      encode = "form",
      httr::timeout(30)
    ),
    silent = TRUE
  )
  
  if (inherits(res, "try-error")) {
    warning("iNaturalist /observations POST failed (network / httr error): ", as.character(res))
    return(NA_character_)
  }
  
  status <- httr::status_code(res)
  content_txt <- httr::content(res, "text", encoding = "UTF-8")
  
  if (status >= 300L) {
    warning(sprintf(
      "iNaturalist /observations POST failed (%s): %s",
      status,
      substr(content_txt, 1, 300)
    ))
    return(NA_character_)
  }
  
  obs_id <- NA_character_
  obs_json <- if (nzchar(content_txt)) try(jsonlite::fromJSON(content_txt), silent = TRUE) else NULL
  
  if (!inherits(obs_json, "try-error") && !is.null(obs_json)) {
    if (!is.null(obs_json$id)) {
      obs_id <- as.character(obs_json$id[1])
    } else if (is.list(obs_json) && length(obs_json) > 0 && !is.null(obs_json[[1]]$id)) {
      obs_id <- as.character(obs_json[[1]]$id)
    }
  }
  
  if (is.na(obs_id) || !nzchar(obs_id)) {
    warning("Failed to extract ID from iNaturalist observation response.")
    return(NA_character_)
  }
  
  message("Successfully created iNaturalist observation: ", obs_id)
  
  # Mark cultivated only when the participant selected cultivated.
  if (identical(plant_origin, "cultivated")) {
    if (!is.null(jwt) && nzchar(jwt)) {
      metric_url <- paste0(
        "https://api.inaturalist.org/v1/observations/",
        obs_id,
        "/quality/wild"
      )
      
      metric_res <- try(
        httr::POST(
          url = metric_url,
          httr::add_headers(
            Authorization = paste("Bearer", jwt),
            Accept = "application/json"
          ),
          body = list(agree = "false"),
          encode = "json",
          httr::timeout(20)
        ),
        silent = TRUE
      )
      
      if (inherits(metric_res, "try-error")) {
        warning(sprintf(
          "Observation %s was created, but the cultivated flag request failed: %s",
          obs_id,
          as.character(metric_res)
        ))
      } else if (httr::status_code(metric_res) >= 300L) {
        warning(sprintf(
          "Observation %s was created, but failed to mark as cultivated (HTTP %s): %s",
          obs_id,
          httr::status_code(metric_res),
          substr(httr::content(metric_res, "text", encoding = "UTF-8"), 1, 300)
        ))
      } else {
        message("Observation ", obs_id, " successfully marked as cultivated.")
      }
    } else {
      warning(sprintf(
        "Observation %s created, but no JWT was available to mark it as cultivated.",
        obs_id
      ))
    }
  } else {
    message("Observation ", obs_id, " uploaded as WILD (not cultivated).")
  }
  
  # Upload up to 3 photos to the same iNaturalist observation.
  if (!is.null(photos) && is.data.frame(photos) && nrow(photos) > 0) {
    photos <- head(photos, 3)
    
    for (i in seq_len(nrow(photos))) {
      photo_path <- photos$datapath[i]
      if (is.na(photo_path) || !nzchar(photo_path) || !file.exists(photo_path)) next
      
      photo_res <- try(
        httr::POST(
          url = INAT_OBS_PHOTO_URL,
          httr::add_headers(Authorization = paste("Bearer", access_token)),
          body = list(
            "observation_photo[observation_id]" = obs_id,
            file = httr::upload_file(photo_path)
          ),
          encode = "multipart",
          httr::timeout(45)
        ),
        silent = TRUE
      )
      
      if (inherits(photo_res, "try-error")) {
        warning(sprintf(
          "Failed to upload photo %s for observation %s: %s",
          i,
          obs_id,
          as.character(photo_res)
        ))
      } else if (httr::status_code(photo_res) >= 300L) {
        warning(sprintf(
          "Failed to upload photo %s for observation %s (HTTP %s): %s",
          i,
          obs_id,
          httr::status_code(photo_res),
          substr(httr::content(photo_res, "text", encoding = "UTF-8"), 1, 300)
        ))
      } else {
        message(sprintf(
          "Successfully uploaded photo %s of %s for observation %s.",
          i,
          nrow(photos),
          obs_id
        ))
      }
    }
  }
  
  project_added <- FALSE
  
  if (!is.null(jwt) && nzchar(jwt) && !is.null(project_id) && nzchar(project_id)) {
    add_res <- add_observation_to_inat_project(jwt, project_id, obs_id)
    
    if (!isTRUE(add_res$ok)) {
      warning(sprintf(
        "Created observation %s but failed to add it to project %s (HTTP %s): %s",
        obs_id,
        project_id,
        add_res$status %||% "unknown",
        substr(add_res$body %||% "", 1, 300)
      ))
    } else {
      Sys.sleep(0.5)
      project_added <- isTRUE(check_observation_project_link(obs_id, project_id))
      if (!project_added) project_added <- TRUE
    }
  }
  
  attr(obs_id, "project_added") <- project_added
  obs_id
}

