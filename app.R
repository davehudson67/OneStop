          collapse = "; "
        )
      } else {
        ""
      },
      
      source_of_plant = if (
        length(source_combined) > 0
      ) {
        paste(
          source_combined,
          collapse = "; "
        )
      } else {
        ""
      },
      
      outside_garden = if (isTRUE(garden_context)) {
        input$outside_garden %||% NA_character_
      } else {
        NA_character_
      },
      
      warning_label = input$warning_label %||%
        NA_character_,
      
      outcompeted = input$outcompeted %||%
        NA_character_,
      
      coverage_dafor = input$coverage_dafor %||%
        NA_character_,
      
      notes = input$notes %||% "",
      
      # Filled after successful iNaturalist upload
      inat_id = NA_character_,
      
      inat_upload_mode = "none",
      
      plant_origin = input$plant_origin %||%
        "cultivated"
    )
    
    
    new_record_df <- as.data.frame(
      new_record,
      stringsAsFactors = FALSE
    )
    
    
    # ============================================================
    # STEP 1
    # SAVE TO OUR DATABASE FIRST
    #
    # This is the important safety rule:
    # iNaturalist can fail without losing the survey.
    # ============================================================
    
    saved_record_id <- tryCatch(
      
      {
        
        insert_observation_returning_id(
          db_pool,
          new_record_df
        )
        
      },
      
      error = function(e) {
        
        showNotification(
          paste(
            tr(
              "UX_DB_ERROR",
              "Database Error:"
            ),
            conditionMessage(e)
          ),
          type = "error",
          duration = 10
        )
        
        warning(
          "Database save failed: ",
          conditionMessage(e)
        )
        
        NULL
      }
    )
    
    
    # Database is the primary research record.
    # If this failed, do NOT attempt iNaturalist.
    if (is.null(saved_record_id)) {
      return()
    }
    
    
    message(
      "Sentinel Garden record saved to DB with ID: ",
      saved_record_id
    )
    
    
    # ============================================================
    # STEP 2
    # GET iNATURALIST AUTHENTICATION
    # ============================================================
    
    auth <- tryCatch(
      
      {
        
        get_effective_inat_auth(
          user_token = inat_token(),
          user_jwt   = inat_jwt()
        )
        
      },
      
      error = function(e) {
        
        warning(
          "Could not obtain iNaturalist authentication: ",
          conditionMessage(e)
        )
        
        list(
          token = NULL,
          jwt   = NULL,
          mode  = "none"
        )
      }
    )
    
    
    # ============================================================
    # STEP 3
    # TRY iNATURALIST
    #
    # At this point we KNOW that:
    #   - at least one photo exists
    #   - species name exists
    #   - location exists
    # ============================================================
    
    obs_id <- NA_character_
    inat_success <- FALSE
    
    
    if (!is.null(auth$token)) {
      
      obs_id <- tryCatch(
        
        {
          
          push_to_inaturalist(
            token        = auth$token,
            jwt          = auth$jwt,
            project_id   = INAT_PROJECT_ID,
            species_name = species_name_value,
            loc          = list(
              lat = lat_value,
              lon = lon_value
            ),
            photos       = photos,
            plant_origin = input$plant_origin %||%
              "cultivated"
          )
          
        },
        
        error = function(e) {
          
          warning(
            "iNaturalist upload failed: ",
            conditionMessage(e)
          )
          
          NA_character_
        }
      )
      
      
      if (
        !is.null(obs_id) &&
        length(obs_id) > 0 &&
        !is.na(obs_id[1]) &&
        nzchar(as.character(obs_id[1]))
      ) {
        
        obs_id <- as.character(obs_id[1])
        inat_success <- TRUE
      }
    }
    
    
    # ============================================================
    # STEP 4
    # UPDATE THE EXACT DATABASE RECORD WITH iNAT RESULT
    # ============================================================
    
    if (isTRUE(inat_success)) {
      
      tryCatch(
        
        {
          
          DBI::dbExecute(
            db_pool,
            "
          UPDATE observations
          SET inat_id = $1,
              inat_upload_mode = $2
          WHERE id = $3;
          ",
            params = list(
              obs_id,
              auth$mode %||% "unknown",
              as.integer(saved_record_id)
            )
          )
          
        },
        
        error = function(e) {
          
          # Record is already safe.
          # This only means the iNat ID wasn't written back.
          warning(
            paste0(
              "Survey record ",
              saved_record_id,
              " was safely saved, but the database ",
              "could not be updated with iNaturalist ID ",
              obs_id,
              ": ",
              conditionMessage(e)
            )
          )
        }
      )
      
      
    } else if (!is.null(auth$token)) {
      
      # ----------------------------------------------------------
      # iNaturalist was attempted but failed.
      # Record that status for later diagnostics.
      # ----------------------------------------------------------
      
      tryCatch(
        
        {
          
          DBI::dbExecute(
            db_pool,
            "
          UPDATE observations
          SET inat_upload_mode = $1
          WHERE id = $2;
          ",
            params = list(
              paste0(
                auth$mode %||% "unknown",
                "_failed"
              ),
              as.integer(saved_record_id)
            )
          )
          
        },
        
        error = function(e) {
          
          warning(
            "Could not record failed iNaturalist upload status: ",
            conditionMessage(e)
          )
        }
      )
    }
    
    
    # ============================================================
    # STEP 5
    # REFRESH LOCAL DATA
    # ============================================================
    
    records_data(
      load_data(db_pool)
    )
    
    
    # ============================================================
    # STEP 6
    # TELL THE USER WHAT HAPPENED
    # ============================================================
    
    if (isTRUE(inat_success)) {
      
      showNotification(
        tr(
          "UX_SAVE_SUCCESS",
          "Survey saved successfully and uploaded to iNaturalist."
        ),
        type = "message",
        duration = 6
      )
      
    } else if (is.null(auth$token)) {
      
      showNotification(
        tr(
          "UX_SAVE_SUCCESS_NO_INAT",
          "Survey saved successfully. iNaturalist upload was not available, but your survey data has been safely recorded."
        ),
        type = "message",
        duration = 8
      )
      
    } else {
      
      showNotification(
        tr(
          "UX_SAVE_SUCCESS_INAT_FAILED",
          "Survey saved successfully. The iNaturalist upload could not be completed, but your survey data has been safely recorded."
        ),
        type = "warning",
        duration = 10
      )
    }
    
    
    # ============================================================
    # STEP 7
    # RESET THE FORM AND SHOW RESULTS
    # ============================================================
    
    reset_record_inputs()
    
    updateTabsetPanel(
      session,
      "main_tabs",
      selected = "results"
    )
    
    active_tab("results")
    
    session$sendCustomMessage(
      "scroll_to_top",
      list()
    )
  })
  
  output$records_table <- renderDT({
    df <- records_data()
    req(nrow(df) > 0)
    
    display_df <- data.frame(
