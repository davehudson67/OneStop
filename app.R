normalize_language <- function(x) {
  if (is.null(x) || !nzchar(x)) return("en")
  x <- tolower(x)
  if (grepl("^pt", x)) return("pt")
  if (grepl("^fi", x)) return("fi")
  if (grepl("^ro", x)) return("ro")
  if (grepl("^fr", x)) return("fr")
  if (grepl("^nl", x)) return("nl")
  "en"
}

tr_text <- function(id, lang = "en", default = NULL) {
  if (is.null(translations_raw) || !("ID" %in% names(translations_raw))) {
    return(default %||% id)
  }
  col_name <- language_map[[lang]]
  if (is.null(col_name) || !(col_name %in% names(translations_raw))) {
    col_name <- "English Text"
  }
  row <- translations_raw[translations_raw$ID == id, , drop = FALSE]
  if (nrow(row) == 0) return(default %||% id)
  value <- row[[col_name]][1]
  if (is.na(value) || !nzchar(trimws(value))) value <- row[["English Text"]][1]
  if (is.na(value) || !nzchar(trimws(value))) return(default %||% id)
  value
}

get_photo_gps <- function(img_paths) {
  if (!isTRUE(EXIF_AVAILABLE)) return(NULL)
  
  img_paths <- img_paths[
    !is.na(img_paths) &
      nzchar(img_paths) &
      file.exists(img_paths)
  ]
  
  if (length(img_paths) == 0) return(NULL)
  
  for (img in img_paths) {
    gps <- tryCatch(
      exifr::read_exif(
        img,
        tags = c(
          "GPSLatitude",
          "GPSLongitude",
          "GPSLatitudeRef",
          "GPSLongitudeRef"
        ),
        quiet = TRUE
      ),
      error = function(e) NULL
    )
    
    if (is.null(gps) || nrow(gps) == 0) next
    if (!all(c("GPSLatitude", "GPSLongitude") %in% names(gps))) next
    
    lat <- suppressWarnings(as.numeric(gps$GPSLatitude[1]))
    lon <- suppressWarnings(as.numeric(gps$GPSLongitude[1]))
    if (is.na(lat) || is.na(lon)) next
    
    if (
      "GPSLatitudeRef" %in% names(gps) &&
      !is.na(gps$GPSLatitudeRef[1]) &&
      toupper(as.character(gps$GPSLatitudeRef[1])) == "S"
    ) {
      lat <- -abs(lat)
    }
    
    if (
      "GPSLongitudeRef" %in% names(gps) &&
      !is.na(gps$GPSLongitudeRef[1]) &&
      toupper(as.character(gps$GPSLongitudeRef[1])) == "W"
    ) {
      lon <- -abs(lon)
    }
    
    if (
      is.finite(lat) && is.finite(lon) &&
      lat >= -90 && lat <= 90 &&
      lon >= -180 && lon <= 180
    ) {
      return(list(lat = lat, lon = lon, source = "photo"))
    }
  }
  
  NULL
}

plantnet_identify <- function(img_paths, api_key) {
  
  img_paths <- img_paths[
    !is.na(img_paths) &
      nzchar(img_paths) &
      file.exists(img_paths)
  ]
  
  if (length(img_paths) == 0) {
    stop("No valid image files supplied to PlantNet.")
  }
  
  # Maximum of 3 photos in our app
  img_paths <- head(img_paths, 3)
  
  image_files <- lapply(
    img_paths,
    httr::upload_file
  )
  
  # PlantNet expects multiple multipart fields all named "images"
  body <- list()
  
  for (i in seq_along(image_files)) {
    body[[paste0("images", i)]] <- image_files[[i]]
  }
  
  names(body) <- rep("images", length(body))
  
  res <- httr::POST(
    url = "https://my-api.plantnet.org/v2/identify/all",
    query = list(
      `api-key` = api_key,
      `include-related-images` = "true",
      lang = "en"
    ),
    body = body,
    encode = "multipart",
    httr::timeout(60)
  )
  
  if (httr::status_code(res) >= 300) {
    body_txt <- httr::content(
      res,
      "text",
      encoding = "UTF-8"
    )
    
    stop(
      sprintf(
        "PlantNet request failed (HTTP %s): %s",
        httr::status_code(res),
        substr(body_txt, 1, 300)
      )
    )
  }
  
  jsonlite::fromJSON(
    httr::content(
      res,
      "text",
      encoding = "UTF-8"
    )
  )
}

plantnet_parse <- function(payload, top_n = 5) {
  res <- payload$results
  if (is.null(res) || nrow(res) == 0) return(tibble())
  res <- head(res, top_n)
  
  common_names <- vapply(
    res$species$commonNames,
    function(x) if (is.null(x) || length(x) == 0) "-" else paste(x, collapse = ", "),
    FUN.VALUE = character(1)
  )
  
  family_names <- if (!is.null(res$species$family$scientificNameWithoutAuthor)) {
    res$species$family$scientificNameWithoutAuthor
  } else {
    rep("", nrow(res))
  }
  
  image_urls <- vapply(
    seq_len(nrow(res)),
    function(i) {
      imgs <- res$images[[i]]
      if (is.null(imgs) || length(imgs) == 0) return(NA_character_)
      vals <- try(unlist(imgs, use.names = FALSE), silent = TRUE)
      if (inherits(vals, "try-error") || is.null(vals) || length(vals) == 0) return(NA_character_)
      char_vals <- as.character(vals)
      http_vals <- char_vals[grepl("^https?://", char_vals)]
      if (length(http_vals) == 0) return(NA_character_)
      http_vals[1]
    },
    FUN.VALUE = character(1)
  )
  
  tibble(
    Score           = round(res$score, 3),
    Scientific.Name = res$species$scientificNameWithoutAuthor,
    Common.Names    = common_names,
    Family          = family_names,
    ImageURL        = image_urls
  )
}

