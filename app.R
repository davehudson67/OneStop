ensure_db <- function(pool) {
  
  DBI::dbExecute(
    pool,
    "
    CREATE TABLE IF NOT EXISTS observations (
      id INT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      timestamp TIMESTAMP,
      observer_name TEXT,
      include_name TEXT,
      observer_email TEXT,
      site_name TEXT,
      observation_context TEXT,
      grid_cell TEXT,
      latitude FLOAT8,
      longitude FLOAT8,
      species_name TEXT,
      spread_beyond TEXT,
      spread_mode TEXT,
      control_effectiveness TEXT,
      control_methods TEXT,
      disposal_methods TEXT,
      introduction_routes TEXT,
      source_of_plant TEXT,
      outside_garden TEXT,
      warning_label TEXT,
      outcompeted TEXT,
      coverage_dafor TEXT,
      notes TEXT,
      inat_id TEXT,
      inat_upload_mode TEXT,
      plant_origin TEXT
    );
    "
  )
  
  
  # ------------------------------------------------------------
  # Ensure newer columns exist
  # ------------------------------------------------------------
  
  existing_cols <- DBI::dbGetQuery(
    pool,
    "
    SELECT column_name
    FROM information_schema.columns
    WHERE table_name = 'observations';
    "
  )
  
  
  if (!"inat_upload_mode" %in% existing_cols$column_name) {
    
    DBI::dbExecute(
      pool,
      "
      ALTER TABLE observations
      ADD COLUMN inat_upload_mode TEXT;
      "
    )
  }
  
  
  if (!"plant_origin" %in% existing_cols$column_name) {
    
    DBI::dbExecute(
      pool,
      "
      ALTER TABLE observations
      ADD COLUMN plant_origin TEXT;
      "
    )
  }
  
  
  if (!"observation_context" %in% existing_cols$column_name) {

    DBI::dbExecute(
      pool,
      "
      ALTER TABLE observations
      ADD COLUMN observation_context TEXT;
      "
    )
  }


  # ------------------------------------------------------------
  # IMPORTANT:
  # Synchronise PostgreSQL's identity sequence with existing IDs.
  #
  # This fixes errors such as:
  #
  # duplicate key value violates unique constraint observations_pkey
  # Key (id)=(6) already exists
  #
  # This can happen when records were imported, restored or previously
  # inserted in a way that did not advance the identity sequence.
  # ------------------------------------------------------------
  
  tryCatch(
    {
      
      DBI::dbGetQuery(
        pool,
        "
        SELECT setval(
          pg_get_serial_sequence('observations', 'id'),
          COALESCE((SELECT MAX(id) FROM observations), 0) + 1,
          false
        ) AS next_id;
        "
      )
      
    },
    
    error = function(e) {
      
      warning(
        "Could not synchronise observations ID sequence: ",
        conditionMessage(e)
      )
    }
  )
}

load_data <- function(pool) {
  if (!DBI::dbExistsTable(pool, "observations")) return(data.frame())
  df <- DBI::dbGetQuery(pool, "SELECT * FROM observations ORDER BY timestamp DESC;")
  as.data.frame(df, stringsAsFactors = FALSE)
}

