get_inaturalist_project <- function(project_id) {
  if (is.null(project_id) || !nzchar(project_id)) {
    return(list(ok = FALSE, status = NA_integer_, body = "Missing project_id", project = NULL))
  }
  res <- try(
    httr::GET(
      url = paste0("https://api.inaturalist.org/v1/projects/", project_id),
      httr::add_headers(Accept = "application/json"),
      httr::timeout(20)
    ),
    silent = TRUE
  )
  if (inherits(res, "try-error")) {
    return(list(ok = FALSE, status = NA_integer_, body = as.character(res), project = NULL))
  }
  status <- httr::status_code(res)
  body_txt <- httr::content(res, "text", encoding = "UTF-8")
  if (status < 200 || status >= 300) {
    return(list(ok = FALSE, status = status, body = body_txt, project = NULL))
  }
  parsed <- try(jsonlite::fromJSON(body_txt), silent = TRUE)
  if (inherits(parsed, "try-error") || is.null(parsed$results) || length(parsed$results) == 0) {
    return(list(ok = FALSE, status = status, body = body_txt, project = NULL))
  }
  project_obj <- if (is.data.frame(parsed$results)) parsed$results[1, , drop = FALSE] else parsed$results[[1]]
  list(ok = TRUE, status = status, body = body_txt, project = project_obj)
}

get_project_name <- function(project_obj, fallback = "the configured iNaturalist project") {
  if (is.null(project_obj)) return(fallback)
  if (is.data.frame(project_obj) && nrow(project_obj) > 0) {
    if ("title" %in% names(project_obj) && !is.na(project_obj$title[1]) && nzchar(project_obj$title[1])) return(as.character(project_obj$title[1]))
    if ("name" %in% names(project_obj) && !is.na(project_obj$name[1]) && nzchar(project_obj$name[1])) return(as.character(project_obj$name[1]))
  }
  if (is.list(project_obj)) {
    if (!is.null(project_obj$title) && nzchar(as.character(project_obj$title[1]))) return(as.character(project_obj$title[1]))
    if (!is.null(project_obj$name) && nzchar(as.character(project_obj$name[1]))) return(as.character(project_obj$name[1]))
  }
  fallback
}

get_inaturalist_jwt <- function(token) {
  if (is.null(token)) return(list(ok = FALSE, status = NA_integer_, body = "Missing token", jwt = NULL))
  access_token <- tryCatch({
    at <- token$access_token
    if (is.null(at) || length(at) == 0) return("")
    as.character(at[1])
  }, error = function(e) "")
  if (!nzchar(access_token)) {
    return(list(ok = FALSE, status = NA_integer_, body = "Missing OAuth access token", jwt = NULL))
  }
  res <- try(
    httr::GET(
      url = "https://www.inaturalist.org/users/api_token",
      httr::add_headers(
        Authorization = paste("Bearer", access_token),
        Accept = "application/json"
      ),
      httr::timeout(20)
    ),
    silent = TRUE
  )
  if (inherits(res, "try-error")) {
    return(list(ok = FALSE, status = NA_integer_, body = as.character(res), jwt = NULL))
  }
  status <- httr::status_code(res)
  body_txt <- httr::content(res, "text", encoding = "UTF-8")
  if (status < 200 || status >= 300) {
    return(list(ok = FALSE, status = status, body = body_txt, jwt = NULL))
  }
  parsed <- try(jsonlite::fromJSON(body_txt), silent = TRUE)
  jwt <- NULL
  if (!inherits(parsed, "try-error") && !is.null(parsed)) jwt <- parsed$api_token %||% parsed$token %||% NULL
  list(ok = !is.null(jwt) && nzchar(jwt), status = status, body = body_txt, jwt = jwt)
}

get_fallback_inat_auth <- function() {
  if (!nzchar(INAT_FALLBACK_ACCESS_TOKEN)) {
    return(list(token = NULL, jwt = NULL, mode = "none"))
  }
  
  fallback_token <- list(access_token = INAT_FALLBACK_ACCESS_TOKEN)
  jwt_res <- get_inaturalist_jwt(fallback_token)
  
  if (!isTRUE(jwt_res$ok)) {
    warning(sprintf(
      "Fallback iNaturalist JWT request failed (HTTP %s): %s",
      jwt_res$status %||% "unknown",
      substr(jwt_res$body %||% "", 1, 200)
    ))
    return(list(token = fallback_token, jwt = NULL, mode = "fallback"))
  }
  
  list(
    token = fallback_token,
    jwt   = jwt_res$jwt,
    mode  = "fallback"
  )
}

get_effective_inat_auth <- function(user_token, user_jwt) {
  if (!is.null(user_token)) {
    return(list(
      token = user_token,
      jwt   = user_jwt,
      mode  = "user"
    ))
  }
  get_fallback_inat_auth()
}

